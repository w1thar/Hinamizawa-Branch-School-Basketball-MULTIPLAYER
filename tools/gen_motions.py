"""Generates src/game/player_motions.cpp from the typed Ghidra output of the Player::Motion_*
functions (pure keyframe data). Every float literal is checked against the 32-bit immediates in
the function's assembly so the generated constants are bit-exact.

usage: python gen_motions.py <reference/ghidra> <reference/ghidra_asm> <out.cpp>
"""
import glob
import os
import re
import struct
import sys

ref_dir, asm_dir, out_path = sys.argv[1:4]


def f32_bits(text):
    return struct.unpack("<I", struct.pack("<f", float(text)))[0]


def fmt_float(text, imm_set, where):
    bits = f32_bits(text)
    if bits not in imm_set:
        raise SystemExit(f"{where}: literal {text} (0x{bits:08x}) not found among asm immediates")
    lit = text if ("." in text or "e" in text) else text + ".0"
    return lit + "f"


body_out = []
for path in sorted(glob.glob(os.path.join(ref_dir, "*_Player__Motion_*.c"))):
    base = os.path.basename(path)[:-2]
    addr, name = base.split("_Player__")
    asm = open(os.path.join(asm_dir, base + ".asm"), encoding="utf-8").read()
    imm = {int(x, 16) for x in re.findall(r"MOV dword ptr \[[^\]]+\],(0x[0-9a-f]+)", asm)}
    imm |= {0}
    src = open(path, encoding="utf-8").read()
    m = re.search(r"\{\n(.*)\n\}\s*$", src, re.S)
    body = m.group(1)
    lines = []
    for ln in body.splitlines():
        if not ln.strip():
            continue
        ln = ln.replace("_memset(", "memset(")
        ln = re.sub(r"this->keys->pose->", "this->keys[0].pose[0].", ln)
        ln = re.sub(r"this->keys->", "this->keys[0].", ln)
        ln = re.sub(r"\)->", ").", ln) if False else ln
        ln = re.sub(r"\((this->keys\[[^\]]+\]\.pose(?:\[[^\]]+\])?)->", r"(\1.", ln)
        ln = re.sub(r"\(this->keys\[(\w+)\]\.pose\)->", r"this->keys[\1].pose[0].", ln)
        ln = re.sub(r"(this->keys\[\w+\]\.pose)->", r"\1[0].", ln)
        # float literal assignments
        def repl(mm):
            return " = " + fmt_float(mm.group(1), imm, f"{name}") + ";"
        ln = re.sub(r" = (-?[0-9]+\.[0-9]+(?:e[-+]?[0-9]+)?|-?[0-9]+\.?[0-9]*e[-+]?[0-9]+);", repl, ln)
        ln = re.sub(r"\b0x([0-9a-f]+)\b", lambda mm: str(int(mm.group(1), 16)), ln)
        lines.append(ln)
    body_out.append(f"// {name} @ 0x{addr}\nvoid Player::{name}()\n{{\n" + "\n".join(lines) + "\n}\n")

header = """// GENERATED by tools/gen_motions.py from the Ghidra decompile of Player::Motion_* (0x42df38..0x4312d5).
// Keyframe poses for the character animations; values are bit-exact copies of the originals.
#include <cstring>

#include "game/player.h"

"""
open(out_path, "w", encoding="utf-8").write(header + "\n".join(body_out))
print(f"wrote {len(body_out)} motions to {out_path}")
